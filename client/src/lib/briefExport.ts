export type ExportableFeatureGapSummary = {
  cacheStatus: "generated" | "cached";
  perspective: string;
  model: string;
  gaps: Array<{
    theme: string;
    evidenceCount: number;
    title: string;
    whyNow: string;
    recommendedFeature: string;
  }>;
};

export function buildFeatureGapBrief(input: {
  filter: string;
  sampleSize: number;
  summary: ExportableFeatureGapSummary;
}): string {
  const { filter, sampleSize, summary } = input;
  const lines = [
    "# Signal Ledger — Feature-gap brief",
    "",
    `**Evidence filter:** ${filter}`,
    `**Research sample:** ${sampleSize} cited public-review excerpts`,
    `**Summary source:** ${summary.cacheStatus === "cached" ? "Validated cached analysis" : "Fresh AI analysis"}`,
    "",
    "## Strategy read",
    summary.perspective,
    "",
    "## Top three feature gaps",
    "",
    ...summary.gaps.flatMap((gap, index) => [
      `### ${index + 1}. ${gap.title}`,
      `**Theme:** ${gap.theme} (${gap.evidenceCount} mentions)`,
      "",
      gap.whyNow,
      "",
      `**Recommended build:** ${gap.recommendedFeature}`,
      "",
    ]),
    "---",
    "Generated by Signal Ledger from the active coded evidence view. This brief is directional and not a statistical market ranking.",
  ];
  return lines.join("\n");
}
